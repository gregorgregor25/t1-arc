const { withSettingsGradle } = require('expo/config-plugins');

const MARKER = '// @generated by with-t1arc-wear';
const WEAR_PROJECT_LINES = [
  MARKER,
  "include ':wear', ':watchface-meridian', ':watchface-chronograph', ':watchface-orbit'",
  "project(':wear').projectDir = new File(rootProject.projectDir, '../wear/companion')",
  "project(':watchface-meridian').projectDir = new File(rootProject.projectDir, '../wear/watchface-meridian')",
  "project(':watchface-chronograph').projectDir = new File(rootProject.projectDir, '../wear/watchface-chronograph')",
  "project(':watchface-orbit').projectDir = new File(rootProject.projectDir, '../wear/watchface-orbit')",
];
const MANAGED_PROJECT_LINES = new Set(WEAR_PROJECT_LINES.slice(1));

function injectT1ArcWearProjects(contents) {
  const lineEnding = contents.includes('\r\n') ? '\r\n' : '\n';
  const retainedLines = [];
  let insideManagedBlock = false;

  for (const line of contents.split(/\r?\n/)) {
    if (line === MARKER) {
      insideManagedBlock = true;
      continue;
    }
    if (insideManagedBlock && MANAGED_PROJECT_LINES.has(line)) continue;
    insideManagedBlock = false;
    retainedLines.push(line);
  }

  const retained = retainedLines.join(lineEnding).trimEnd();
  const separator = retained ? `${lineEnding}${lineEnding}` : '';
  return `${retained}${separator}${WEAR_PROJECT_LINES.join(lineEnding)}${lineEnding}`;
}

/**
 * Keeps the tracked Wear OS projects attached to Expo's generated Android
 * project. The wearable source lives outside /android so a clean prebuild
 * cannot silently delete it.
 */
function withT1ArcWear(config) {
  return withSettingsGradle(config, (androidConfig) => {
    if (androidConfig.modResults.language !== 'groovy') {
      throw new Error(
        'T1 Arc Wear configuration currently expects Groovy settings.gradle.',
      );
    }

    androidConfig.modResults.contents = injectT1ArcWearProjects(
      androidConfig.modResults.contents,
    );
    return androidConfig;
  });
}

module.exports = withT1ArcWear;
module.exports.injectT1ArcWearProjects = injectT1ArcWearProjects;
