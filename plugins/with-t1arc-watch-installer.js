const { withAppBuildGradle } = require('expo/config-plugins');
const MARKER = '// @generated by with-t1arc-watch-installer';

function injectWatchInstaller(contents) {
  if (contents.includes(MARKER)) return contents;
  return `${contents.trimEnd()}\n\n${MARKER}\napply from: rootProject.file('../scripts/gradle/t1arc-watch-installer.gradle')\n`;
}

module.exports = config => withAppBuildGradle(config, result => {
  if (result.modResults.language !== 'groovy') throw new Error('Watch installer requires Groovy Gradle.');
  result.modResults.contents = injectWatchInstaller(result.modResults.contents);
  return result;
});
module.exports.injectWatchInstaller = injectWatchInstaller;
